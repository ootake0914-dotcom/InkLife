// ビットマップ装備 (1,2,3,5,6,7,9,10) の網羅をコンパイル時検証。新装備追加時は行追加。
static constexpr bool partHasGear(uint8_t g) {
  for (unsigned i = 0; i < sizeof(PART_ROWS) / sizeof(PART_ROWS[0]); i++)
    if (PART_ROWS[i].gear == g) return true;
  return false;
}
